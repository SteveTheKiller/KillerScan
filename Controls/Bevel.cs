    /// <summary>
    /// The family bevel for wordmarks and headings: the text keeps its own color, its upper-left
    /// edges catch a slightly lighter shade and its lower-right edges a slightly darker one, so it
    /// reads as raised lettering instead of text with a dark outline. Set Bevel.Enabled on a
    /// TextBlock (HeadingAccent turns it on for headings). The edge is one device pixel at any
    /// size: thin hand-drawn strokes turn pale when the lit edge is any wider.
    /// </summary>
    public static class Bevel
    {
        public static readonly DependencyProperty EnabledProperty = DependencyProperty.RegisterAttached(
            "Enabled", typeof(bool), typeof(Bevel), new PropertyMetadata(false, OnEnabledChanged));

        public static bool GetEnabled(DependencyObject element) => (bool)element.GetValue(EnabledProperty);
        public static void SetEnabled(DependencyObject element, bool value) => element.SetValue(EnabledProperty, value);

        /// <summary>How much the lit edge moves toward white and the shaded edge toward black.</summary>
        internal const double Light = 0.12, Shade = 0.22;

        private static void OnEnabledChanged(DependencyObject element, DependencyPropertyChangedEventArgs args)
        {
            if (element is not FrameworkElement target) return;
            target.Loaded -= Refresh;
            target.SizeChanged -= Refresh;
            if (!(bool)args.NewValue)
            {
                target.ClearValue(UIElement.EffectProperty);
                return;
            }
            target.Loaded += Refresh;
            target.SizeChanged += Refresh;
            Apply(target);
        }

        private static void Refresh(object sender, RoutedEventArgs args) => Apply((FrameworkElement)sender);

        private static void Apply(FrameworkElement target)
        {
            double size = target is TextBlock text ? text.FontSize : 14;
            target.Effect = SystemParameters.HighContrast ? null : For(target, size);
        }

        /// <summary>A frozen bevel one device pixel deep on the visual's monitor.</summary>
        internal static Effect For(Visual visual, double fontSize)
        {
            double scale = VisualTreeHelper.GetDpi(visual).DpiScaleX;
            var effect = new BevelEffect(scale, Light, Shade);
            if (effect.CanFreeze) effect.Freeze();
            return effect;
        }

