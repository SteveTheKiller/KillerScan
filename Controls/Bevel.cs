        //       float4 c = tex2D(input, uv);
        //       float2 d = (ddxDdy.xy + ddxDdy.zw) * depth;
        //       float lit = saturate(c.a - tex2D(input, uv - d).a);
        //       float dark = saturate(c.a - tex2D(input, uv + d).a);
