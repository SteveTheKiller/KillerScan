            // Declared after Bytecode: static fields initialize in order.
            private static readonly PixelShader Shader = LoadShader();

            public Outline(Color rim, double radius)
            {
                PixelShader = Shader;
                DdxUvDdyUvRegisterIndex = 0;
                PaddingLeft = PaddingTop = PaddingRight = PaddingBottom = radius + 1;
                SetValue(RimColorProperty, rim);
                SetValue(RadiusProperty, radius);
                // A value equal to the default raises no change, so push every register once.
                UpdateShaderValue(InputProperty);
                UpdateShaderValue(RimColorProperty);
                UpdateShaderValue(RadiusProperty);
            }

            public Color RimColor => (Color)GetValue(RimColorProperty);
            public double Radius => (double)GetValue(RadiusProperty);

            private static PixelShader LoadShader()
            {
                var shader = new PixelShader();
                shader.SetStreamSource(new MemoryStream(Bytecode));
                shader.Freeze();
                return shader;
            }
        }
