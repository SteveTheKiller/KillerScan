        //       a = max(a, tex2D(input, uv - d1).a);
        //       a = max(a, tex2D(input, uv + d2).a);
        //       a = max(a, tex2D(input, uv - d2).a);
        //       a = max(a, tex2D(input, uv + rx * 0.5).a);
        //       a = max(a, tex2D(input, uv - rx * 0.5).a);
        //       a = max(a, tex2D(input, uv + ry * 0.5).a);
