    /// <summary>Uses the logo color for headings, raised with the family bevel.</summary>
    public static class HeadingAccent
    {
        public static readonly DependencyProperty EnabledProperty = DependencyProperty.RegisterAttached(
            "Enabled", typeof(bool), typeof(HeadingAccent), new PropertyMetadata(false, OnEnabledChanged));

        public static bool GetEnabled(DependencyObject element) => (bool)element.GetValue(EnabledProperty);
        public static void SetEnabled(DependencyObject element, bool value) => element.SetValue(EnabledProperty, value);

        private static readonly IValueConverter Converter = new HeadingOutlineConverter();

        private static void OnEnabledChanged(DependencyObject element, DependencyPropertyChangedEventArgs args)
        {
            if (element is not TextBlock text) return;
            text.Loaded -= RefreshOutline;
            text.SizeChanged -= RefreshOutline;
            if (!(bool)args.NewValue)
            {
                text.ClearValue(TextBlock.ForegroundProperty);
                text.ClearValue(UIElement.EffectProperty);
                return;
            }
            text.SetResourceReference(TextBlock.ForegroundProperty, "AccentLogo");
            text.SetBinding(UIElement.EffectProperty, new Binding(nameof(TextBlock.Foreground))
            {
                RelativeSource = RelativeSource.Self,
                Converter = Converter,
                ConverterParameter = text,
            });
            text.Loaded += RefreshOutline;
            text.SizeChanged += RefreshOutline;
        }

        private static void RefreshOutline(object sender, RoutedEventArgs args) =>
            ((TextBlock)sender).GetBindingExpression(UIElement.EffectProperty)?.UpdateTarget();

        private sealed class HeadingOutlineConverter : IValueConverter
        {
            public object? Convert(object value, Type targetType, object parameter, CultureInfo culture)
            {
                // Raised lettering in the heading's own color, not a dark edge around it (Bevel.cs).
                if (SystemParameters.HighContrast || value is not SolidColorBrush || parameter is not TextBlock text) return null;
                return Bevel.For(text, text.FontSize);
            }

            public object ConvertBack(object value, Type targetType, object parameter, CultureInfo culture) => Binding.DoNothing;
        }
    }

    /// <summary>
    /// Light with the Yellow accent keeps its accent yellow and draws a thin gray outline around every
    /// yellow text and glyph so it reads on the light surfaces. A theme turns it on by giving
    /// WordmarkAccentShadowOpacity a value above 0; every other theme leaves that at 0 and nothing
    /// changes. Text that already draws its own effect, such as a wordmark halo copy, keeps it.
    /// Call Initialize once at startup.
    /// </summary>
    internal static class AccentShadow
    {
        /// <summary>The outline color, a medium gray that rims the yellow without going black.</summary>
        internal static readonly Color RimColor = Color.FromRgb(0x5A, 0x5A, 0x5A);

        /// <summary>The outline width in device-independent pixels.</summary>
        internal const double RimWidth = 1.0;

        private static bool _initialized;
        private static readonly IValueConverter Converter = new OutlineConverter();
        private static readonly DependencyProperty TrackedProperty = DependencyProperty.RegisterAttached(
            "Tracked", typeof(bool), typeof(AccentShadow), new PropertyMetadata(false));
        private static readonly string[] AccentKeys =
            { "PrimaryBrush", "PrimaryHoverBrush", "PrimaryPressedBrush", "AccentLogo", "OutlineBtnBrush",
              "HeaderLineBrush", "SelectionAccent", "RadioAccent" };

        internal static void Initialize()
        {
            if (_initialized) return;
            _initialized = true;
            EventManager.RegisterClassHandler(typeof(TextBlock), FrameworkElement.SizeChangedEvent,
                new SizeChangedEventHandler(OnTextSizeChanged), true);
        }

        private static void OnTextSizeChanged(object sender, SizeChangedEventArgs args)
        {
            if (sender is not TextBlock text || (bool)text.GetValue(TrackedProperty)) return;
            text.SetValue(TrackedProperty, true);
            if (text.Effect != null || BindingOperations.IsDataBound(text, UIElement.EffectProperty)) return;
            // Bound to the text's own color, so hover and selection colors and theme changes add or
            // remove the outline as the color changes. The DPI scale keeps the rim one unit wide on
            // every monitor.
            text.SetBinding(UIElement.EffectProperty, new Binding(nameof(TextBlock.Foreground))
            {
                RelativeSource = RelativeSource.Self,
                Converter = Converter,
                ConverterParameter = VisualTreeHelper.GetDpi(text).DpiScaleX,
            });
        }

        /// <summary>True when the theme asks for the outline and the color is one of its accent colors.</summary>
        internal static bool Applies(Brush? brush)
        {
            var app = Application.Current;
            if (app == null || brush is not SolidColorBrush solid) return false;
            if (!(app.TryFindResource("WordmarkAccentShadowOpacity") is double opacity) || opacity <= 0) return false;
            foreach (string key in AccentKeys)
                if (app.TryFindResource(key) is SolidColorBrush accent && accent.Color == solid.Color)
                    return true;
            return false;
        }

        private sealed class OutlineConverter : IValueConverter
        {
            private readonly Dictionary<double, Outline> _byScale = new Dictionary<double, Outline>();

            public object? Convert(object value, Type targetType, object parameter, CultureInfo culture)
            {
                if (!Applies(value as Brush)) return null;
                double scale = parameter is double d && d > 0 ? d : 1.0;
                if (!_byScale.TryGetValue(scale, out var effect))
                {
                    effect = new Outline(RimColor, RimWidth * scale);
                    if (effect.CanFreeze) effect.Freeze();
                    _byScale[scale] = effect;
                }
                return effect;
            }

            public object ConvertBack(object value, Type targetType, object parameter, CultureInfo culture) =>
                Binding.DoNothing;
        }

