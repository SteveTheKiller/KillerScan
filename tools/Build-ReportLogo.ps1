# Builds Resources\report-logo.svg and Services\ReportLogoColors.cs from the published
# scan-landing\brand\killerscan-logo-*.svg files, so HTML reports carry their logo instead of
# loading it from killerscan.net (U006).
#
# Every published variant is the same artwork in different colors: slot 0 is the "Killer" text,
# slots 1 to 3 are the "Scan" shades, and light-yellow alone adds an outline layer behind "Scan"
# (slot 4) so yellow reads on white. Light themes drop the drop shadow. The template keeps the
# outline layer and the shadow, and each report theme switches them through CSS variables.
# Run it again whenever the brand SVGs change.

$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$brand = Join-Path $repo 'scan-landing\brand'
$norm = { param($t) $t -replace '(?s)<defs>.*?</defs>\r?\n?', '' -replace '\s*filter="url\(#ds\)"', '' }
$outlinePattern = '(?s)<g fill="#5a5a5a" stroke="#5a5a5a".*?</g>\r?\n'

# Slot order of every color occurrence, taken from a variant without the outline layer.
$base = & $norm (Get-Content (Join-Path $brand 'killerscan-logo-black-green.svg') -Raw)
$distinct = [System.Collections.Generic.List[string]]::new()
$slots = foreach ($m in [regex]::Matches($base, '#[0-9A-Fa-f]{6}')) {
    $v = $m.Value.ToLower(); if (-not $distinct.Contains($v)) { $distinct.Add($v) }; $distinct.IndexOf($v)
}

$rows = [ordered]@{}
foreach ($file in Get-ChildItem $brand -Filter 'killerscan-logo-*.svg' | Sort-Object Name) {
    $raw = Get-Content $file.FullName -Raw
    $text = & $norm $raw
    $outline = [regex]::Match($text, $outlinePattern)
    $slot4 = 'none'
    if ($outline.Success) { $slot4 = '#5a5a5a'; $text = $text.Remove($outline.Index, $outline.Length) }
    if (($text -replace '#[0-9A-Fa-f]{6}', '#') -ne ($base -replace '#[0-9A-Fa-f]{6}', '#')) { throw "$($file.Name) is not the shared artwork." }
    $hex = @([regex]::Matches($text, '#[0-9A-Fa-f]{6}') | ForEach-Object { $_.Value.ToLower() })
    $map = @{}
    for ($i = 0; $i -lt $hex.Count; $i++) {
        if ($map.ContainsKey($slots[$i]) -and $map[$slots[$i]] -ne $hex[$i]) { throw "$($file.Name) uses two colors in one slot." }
        $map[$slots[$i]] = $hex[$i]
    }
    $rows[$file.BaseName -replace '^killerscan-logo-', ''] = [pscustomobject]@{
        Colors = @($map[0], $map[1], $map[2], $map[3], $slot4); Shadow = $raw -match 'filter="url\(#ds\)"'
    }
}

# The template: light-yellow's artwork (it has the outline layer) with the shadow put back and
# each color replaced by its slot variable.
$yellow = & $norm (Get-Content (Join-Path $brand 'killerscan-logo-light-yellow.svg') -Raw)
$dark = Get-Content (Join-Path $brand 'killerscan-logo-black-green.svg') -Raw
$defs = [regex]::Match($dark, '(?s)<defs>.*?</defs>\r?\n').Value
$order = @(0) + @(4, 4) + @($slots | Select-Object -Skip 1)
$n = @{ i = 0 }
$template = [regex]::Replace($yellow, 'fill="#[0-9A-Fa-f]{6}"( stroke="#[0-9A-Fa-f]{6}")?', {
    param($m)
    $slot = $order[$n.i]; $n.i += $(if ($m.Groups[1].Success) { 2 } else { 1 })
    if ($m.Groups[1].Success) { "style=`"fill:var(--lg$slot);stroke:var(--lg$slot)`"" } else { "style=`"fill:var(--lg$slot)`"" }
})
if ($n.i -ne $order.Count) { throw "Template has $($n.i) color uses, expected $($order.Count)." }
$template = $template -replace '(<svg[^>]*>\r?\n)', ('$1' + $defs.Replace('$', '$$'))
$template = $template -replace '<g transform="translate\(40,1240\) scale\(1,-1\)">', '<g class="lgshadow" transform="translate(40,1240) scale(1,-1)" filter="url(#ds)">'
$template = $template -replace '<g style="fill:var\(--lg4\);stroke:var\(--lg4\)"', '<g class="lgoutline" style="fill:var(--lg4);stroke:var(--lg4)"'
$template = ($template -split "\r?\n" | ForEach-Object { $_.Trim() } | Where-Object { $_ }) -join "`n"
[IO.File]::WriteAllText((Join-Path $repo 'Resources\report-logo.svg'), $template + "`n", [Text.UTF8Encoding]::new($false))

$lines = foreach ($name in $rows.Keys) {
    $r = $rows[$name]
    "            [`"$name`"] = new[] { `"" + ($r.Colors -join '", "') + "`", `"" + $(if ($r.Shadow) { '1' } else { '0' }) + "`" },"
}
$cs = @"
// Generated by tools\Build-ReportLogo.ps1 from scan-landing\brand. Do not edit by hand.
using System.Collections.Generic;

namespace KillerScan.Services
{
    internal static class ReportLogoColors
    {
        /// <summary>Per logo variant: the five slot colors (--lg0 to --lg4), then "1" for the drop shadow.</summary>
        internal static readonly IReadOnlyDictionary<string, string[]> Variants = new Dictionary<string, string[]>
        {
$($lines -join "`n")
        };
    }
}
"@
[IO.File]::WriteAllText((Join-Path $repo 'Services\ReportLogoColors.cs'), $cs.Replace("`r`n", "`n") + "`n", [Text.UTF8Encoding]::new($false))
"Wrote $($rows.Count) variants; template $([Math]::Round($template.Length / 1KB)) KB."
