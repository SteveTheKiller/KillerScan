"""Print website shortcut data from the application's one binding table. --check verifies it."""
from pathlib import Path
import json,re,sys,xml.etree.ElementTree as ET

root=Path(__file__).resolve().parent.parent
source=(root/'Shell/Shortcuts.cs').read_text(encoding='utf-8')
table=source.split('ShortcutRows =',1)[1].split('];',1)[0]
rows=re.findall(r'\("([^"]+)",\s*"([^"]+)",\s*"([^"]+)"\)',table)
assert rows
locales={}
for file in sorted((root/'Strings').glob('*.xaml')):
    locales[file.stem]={node.attrib['{http://schemas.microsoft.com/winfx/2006/xaml}Key']:node.text or ''
        for node in ET.parse(file).getroot() if '{http://schemas.microsoft.com/winfx/2006/xaml}Key' in node.attrib}
entries=[]
for gesture,key,category in rows:
    assert all(key in values for values in locales.values()), key
    scope = ('Str_Workspace_Terminal' if key.startswith('Str_Term_') else
        'Str_Services_Title' if key.startswith('Str_Services_Copy') else
        'Str_Profiles_Title' if key.startswith('Str_Profiles_') and key!='Str_Profiles_Title' else
        'Str_View_KeepAlive' if key.startswith('Str_Watch_') or key=='Str_Diag_Refresh' else
        'Str_History_Title' if key in ('Str_History_CopyDetails','Str_History_ToggleView') else None)
    entries.append({'gesture':gesture,'category':category,'labels':{locale:
        ((values['Str_TT_TopologyOrder']+' ') if gesture in ['Ctrl + '+str(i) for i in range(1,5)] else '')+
        ((values[scope]+': ') if scope else '')+values[key] for locale,values in locales.items()}})
output='// Generated by build/shortcut-catalog.py from Shell/Shortcuts.cs and Strings.\nwindow.KS_SHORTCUTS = '+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+';\n'
target=root/'scan-landing/shortcuts.generated.js'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8')==output,'Regenerate shortcuts.generated.js from the current app table.'
    print(f'PASS: {len(entries)} bindings and {len(locales)} locales match the app shortcut table.')
else:
    sys.stdout.buffer.write(output.encode('utf-8'))
